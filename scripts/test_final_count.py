sec_distance = """Food sold through distance selling (websites, phone orders, and delivery apps like Deliveroo, Uber Eats, or Just Eat) is governed by separate legal rules under the Food Information Regulations.

When selling food remotely:
• Before purchase: Allergen information must be available before payment (such as via online menu allergen filters or verbal confirmation over the phone).
• At delivery or collection: Clear allergen information must accompany the food at physical handover (such as printed order receipts or item container stickers).

Key operational distinctions:
• In-store PPDS display: Full ingredient list and emphasised allergens affixed directly to the package.
• Telephone order: Verbal allergen declaration before payment, followed by written notice upon delivery.
• Website or app delivery: Digital allergen declarations during ordering, plus written verification at handover.
• Customer collection: If packaged after ordering, non-prepacked rules apply; if packaged in advance, provide clear allergen documentation."""

sec_supplier_changes = """Ingredient substitutions create serious risk of accidental allergen exposure. Food businesses must review product labels immediately when:

• An ingredient brand changes: Different brands often use different oils, thickeners, or fillers.
• A supplier changes: Wholesalers may substitute equivalent lines without notice.
• A kitchen recipe changes: Modifying dressings or seasonings alters ingredient weight order.
• A sauce or seasoning changes: Switching bouillon or sauces can introduce undeclared celery, gluten, or soya.
• A product becomes prepacked before sale: Items pre-portioned into grab-and-go packaging transition to PPDS.
• An allergen statement changes: Manufacturers may revise factory cross-contact warnings."""


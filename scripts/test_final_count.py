direct_answer = """Prepacked for Direct Sale (PPDS) food is food packaged on the premises before a customer selects or orders it. Under Natasha’s Law (the Food Information Amendment Regulations 2019), any UK food business selling PPDS food—including cafes, bakeries, delis, restaurants, and takeaways—must clearly label each item with the name of the food, a complete ingredients list, and any of the 14 statutory allergens emphasised. Businesses must verify current official guidance for their specific operational circumstances."""

sec_what_is = """Prepacked for Direct Sale (PPDS) food meets three criteria: it is packaged before selection or ordering, packaged on the same premises where sold, and offered directly to the final consumer.

Common commercial examples of PPDS food:
• Sandwiches and wraps boxed or wrapped in a cafe before display.
• Salads and pasta pots portioned and lidded in advance.
• Bakery items like cookies, muffins, or pasties packed on-site.
• Food prepared and packaged on-site for customer takeaway collection.

Distinguishing PPDS from other food sales:
• Non-prepacked food: Loose food sold without packaging, such as open bakery counter items.
• Food packed after ordering: Food packaged only after customer choice, such as made-to-order sandwiches.
• Prepacked food: Food packaged at a separate manufacturing site, requiring standard prepack labels.
• Distance selling: Food ordered online or by phone, following remote allergen rules."""

sec_must_include = """A compliant PPDS label must present mandatory details legibly on the package:

• Name of the Food: An accurate description identifying the food product.
• Complete Ingredients List: All recipe ingredients listed in descending order by weight.
• Emphasised Allergens: Any of the 14 statutory allergens highlighted within the ingredients list.
• Clear Legibility: Easily readable text not obscured by artwork or stickers.
• Responsible Business Information: Name and address of the responsible food business operator.

Official guidance allows flexibility in physical label layout (such as printed adhesive labels or wrappers), provided required elements remain prominent and legible."""

sec_14_allergens = """UK food regulations require clear declaration of the 14 statutory allergens:

• Celery (stalks, leaves, seeds, and celery salt)
• Cereals containing gluten (wheat, rye, barley, spelt, oats)
• Crustaceans (prawns, crabs, lobsters, scampi)
• Eggs (fresh, liquid, and dried egg products)
• Fish (fresh, frozen, canned, and fish sauces)
• Lupin (lupin flour, seeds, and bakery blends)
• Milk (milk, cheese, butter, cream, and powders)
• Molluscs (mussels, oysters, squid, clams)
• Mustard (liquid, powder, seeds, and dressings)
• Nuts / Tree nuts (almonds, hazelnuts, walnuts, cashews, pecans, Brazil nuts, pistachios, macadamias)
• Peanuts (groundnuts, butter, and peanut oils)
• Sesame (sesame seeds, tahini, and sesame oils)
• Soya (soybeans, soy sauce, tofu, soya lecithin)
• Sulphur dioxide and sulphites (concentrations >10 mg/kg or 10 mg/litre)

Allergens must be identified when present as standalone ingredients or as components of compound ingredients."""

sec_compound = """A compound ingredient consists of multiple sub-ingredients. Under Natasha’s Law, kitchen operators cannot list only the compound name—they must declare sub-ingredients and identify hidden allergens.

Common kitchen compound ingredients:
• Mayonnaise: Typically contains pasteurised egg and mustard.
• Pesto: Often contains cheese (milk) and pine nuts or cashews (tree nuts).
• Bread: Frequently contains wheat flour (gluten), soya, or sesame seeds.
• Stock cubes: Commonly contain celery and wheat gluten.
• Commercial sauces: Often contain soya, fish, wheat, mustard, or sulphites.
• Spice mixes: May incorporate mustard powder or ground celery seeds.
• Chocolate: Commonly contains milk powder and soya lecithin.
• Marinades: Frequently incorporate soy sauce (soya, wheat) or fish sauce.
• Worcestershire sauce: Contains barley malt vinegar (gluten) and anchovies (fish).
• Composite fillings: Fillings like chicken mayo combine proteins with allergen-rich binders.

Businesses must verify physical supplier trade specifications rather than guessing contents."""

sec_how_to = """Follow these 9 steps to produce compliant PPDS food labels:

1. Identify the product: Confirm whether the item meets PPDS criteria before packaging.
2. Record every recipe ingredient: Document all raw ingredients and compound components.
3. Check supplier specifications: Inspect manufacturer labels and ingredient data sheets.
4. Identify allergens: Flag any of the 14 statutory allergens in raw items and sub-ingredients.
5. Prepare the ingredients list: Order ingredients in descending order of incoming weight.
6. Emphasise allergens clearly: Highlight allergens in BOLD capitals or contrasting text.
7. Add business details: Include the food name and responsible business operator address.
8. Check before printing: Proofread the completed label against kitchen stock.
9. Review when ingredients change: Re-audit the label whenever recipes or brands are substituted."""


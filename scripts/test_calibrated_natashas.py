direct_answer = """Prepacked for Direct Sale (PPDS) food is food packaged on the premises before a customer selects or orders it. Under Natasha’s Law (the Food Information Amendment Regulations 2019), any UK food business selling PPDS food—including cafes, bakeries, delis, restaurants, and takeaways—must clearly label each item with the name of the food, a complete ingredients list, and any of the 14 statutory allergens emphasised. Businesses must verify current official guidance for their specific operational circumstances."""

sec_what_is = """Prepacked for Direct Sale (PPDS) food meets three criteria: it is packaged before selection or ordering, packaged on the same premises where sold, and offered directly to consumers.

Common commercial PPDS examples:
• Display Sandwiches & Wraps: Sandwiches wrapped in film or bags in a cafe before customer arrival.
• Pre-Boxed Salads: Pasta bowls and salad pots portioned and lidded in advance.
• Packaged Bakery Goods: Cookies, pasties, or breads bagged on-site for retail shelves.
• Takeaway Collection Items: Food packaged on-site by a takeaway before customer pickup.

Distinguishing PPDS from other sales:
• Non-Prepacked: Loose counter food sold without packaging.
• Packed After Ordering: Items packaged after customer request, like bespoke sandwiches.
• Prepacked (Off-Site): Food packaged at a separate facility under full prepack rules.
• Distance Selling: Food ordered online or by phone, following remote allergen rules."""

sec_must_include = """Under UK food labelling rules, a compliant PPDS label must present mandatory details legibly on the package:

1. Name of the Food: Clear descriptive name accurately identifying the product.
2. Complete Ingredients List: All recipe ingredients listed in descending order by weight at preparation.
3. Emphasised Statutory Allergens: Any of the 14 statutory allergens highlighted in BOLD capitals or contrasting text every time they appear.
4. Legibility & Business Details: Easily readable text with responsible operator contact details where required.

Official guidance allows flexibility in physical label layout (such as printed adhesive labels or wrappers), provided required elements remain prominent and legible."""


sec_distance = """Food sold through distance selling (websites, phone orders, and delivery apps like Deliveroo, Uber Eats, or Just Eat) is governed by separate legal rules under the Food Information Regulations.

When selling food remotely:
• Before purchase: Allergen information must be available before payment (via online menu filters or verbal declaration over the phone).
• At delivery or collection: Clear written allergen information must accompany the food at physical handover (such as printed receipts or item container stickers).

Key distinctions: In-store PPDS requires full labels affixed directly. Distance selling requires remote declarations plus written handover notices. Items packaged after customer choice follow non-prepacked rules."""


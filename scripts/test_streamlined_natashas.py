direct_answer = """Prepacked for Direct Sale (PPDS) food is food packaged on the premises before a customer selects or orders it. Under Natasha’s Law (the Food Information Amendment Regulations 2019), any UK food business selling PPDS food—including cafes, bakeries, delis, restaurants, and takeaways—must clearly label each item with the name of the food, a complete ingredients list, and any of the 14 statutory allergens emphasised. Businesses must verify current official guidance for their specific operational circumstances."""

sec_what_is = """Prepacked for Direct Sale (PPDS) food meets three criteria: it is packaged before the customer selects or orders it, it is packaged on the same premises from which it is sold, and it is offered directly to the final consumer.

Common commercial examples of PPDS food include:
• Sandwiches and wraps prepared and packaged in a cafe before display.
• Salads and pasta pots boxed and lidded before customer selection.
• Bakery items such as cookies or pasties wrapped on-site for direct sale.
• Food prepared and packaged on-site for customer takeaway collection.

PPDS must be distinguished from other sales categories:
• Non-prepacked food: Loose food sold without packaging, such as loose counter pastries.
• Food packed after ordering: Items packaged after customer request, like a bespoke sandwich.
• Prepacked food: Food packaged at a separate facility, requiring standard prepack labels.
• Distance selling: Food ordered online or by phone, governed by remote allergen rules."""

sec_must_include = """A compliant PPDS label must present mandatory product information clearly and legibly:

• Name of the Food: A descriptive name accurately identifying the product.
• Complete Ingredients List: All recipe ingredients listed in descending order by weight.
• Emphasised Allergens: Any of the 14 statutory allergens highlighted within the ingredients list.
• Clear Legibility: Easily readable text not obscured by packaging artwork.
• Responsible Business Information: Name and address of the food business operator where required.

Official guidance allows flexibility in physical label layout (such as printed adhesive labels or pre-printed wrappers), provided mandatory elements remain prominent and easy to find."""

sec_14_allergens = """UK food legislation identifies 14 statutory allergens requiring declaration:

• Celery: Stalks, leaves, seeds, and celery salt.
• Cereals containing gluten: Wheat, rye, barley, spelt, and oats.
• Crustaceans: Prawns, crabs, lobsters, and scampi.
• Eggs: Fresh, liquid, and dried egg products.
• Fish: Fresh, frozen, canned fish, and fish sauces.
• Lupin: Lupin flour, seeds, and bakery mixes.
• Milk: Milk, cheese, butter, cream, and milk powders.
• Molluscs: Mussels, oysters, squid, and clams.
• Mustard: Mustard flour, seeds, liquid, and dressings.
• Nuts (Tree nuts): Almonds, hazelnuts, walnuts, cashews, pecans, Brazil nuts, pistachios, and macadamias.
• Peanuts: Groundnuts, peanut butter, and peanut oils.
• Sesame: Sesame seeds, tahini, and sesame oils.
• Soya: Soybeans, soy sauce, tofu, and soya lecithin.
• Sulphur dioxide and sulphites: Concentrations exceeding 10 mg/kg or 10 mg/litre.

Allergens must be identified when present as standalone ingredients or as components of compound ingredients."""

sec_compound = """A compound ingredient consists of multiple sub-ingredients. Under Natasha’s Law, kitchen teams cannot simply list the compound name—they must declare sub-ingredients and identify hidden allergens.

Common examples of compound ingredients include:
• Mayonnaise: Typically contains pasteurised egg and mustard.
• Pesto: Often contains cheese (milk) and pine nuts or cashews (tree nuts).
• Bread: Frequently contains wheat flour (gluten), soya, or sesame seeds.
• Stock cubes: Commonly contain celery and wheat gluten.
• Commercial sauces: Often contain soya, fish, wheat, mustard, or sulphites.
• Spice mixes: May incorporate mustard powder or ground celery seeds.
• Chocolate: Commonly contains milk powder and soya lecithin.
• Marinades: Frequently incorporate soy sauce (soya, wheat) or fish sauce.
• Worcestershire sauce: Contains barley malt vinegar (gluten) and anchovies (fish).
• Composite fillings: Fillings like chicken mayo combine proteins with allergen-rich binders.

Businesses must check physical supplier labels and specifications instead of guessing contents."""

sec_how_to = """Follow these 9 steps to create compliant PPDS food labels:

1. Identify the exact food product: Confirm whether the item meets PPDS criteria before packaging.
2. Record every recipe ingredient: Document all raw ingredients and compound components.
3. Check supplier specifications: Inspect manufacturer labels and ingredient data sheets.
4. Identify allergens: Flag any of the 14 statutory allergens in raw items and sub-ingredients.
5. Prepare the ingredients list: Order ingredients in descending order of incoming weight.
6. Emphasise allergens clearly: Highlight allergens in BOLD capitals or contrasting text.
7. Add required business information: Include the food name and responsible business details.
8. Check the label before printing: Proofread the completed label against physical kitchen stock.
9. Review when ingredients change: Re-audit the label whenever recipes or brands are substituted."""

